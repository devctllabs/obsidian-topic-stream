export const PendingFailure: Story = { args: editorArgs(), play: async ({ canvasElement, args }) => {
  const canvas = within(canvasElement);
  await userEvent.click(await canvas.findByText("Advanced"));
  await fireEvent.change(canvas.getByRole("spinbutton", { name: "Candidate limit" }), { target: { value: "70" } });
  await userEvent.click(canvas.getByRole("button", { name: "Save workspace settings" }));
  await expect(canvas.getByRole("button", { name: "Save workspace settings" })).toBeDisabled();
  args.service.workspaceUpdate.calls[0]?.response.reject(new Error("Connection interrupted"));
  await expect(await canvas.findByText("Could not save workspace settings. Your draft is kept.")).toBeVisible();
  await expect(canvas.getByRole("spinbutton", { name: "Candidate limit" })).toHaveValue(70);
} };
export const Conflict: Story = { args: editorArgs(), play: async ({ canvasElement, args }) => {
  const canvas = within(canvasElement);
  await userEvent.click(await canvas.findByText("Advanced"));
  await fireEvent.change(canvas.getByRole("spinbutton", { name: "Candidate limit" }), { target: { value: "70" } });
  await userEvent.click(canvas.getByRole("button", { name: "Save workspace settings" }));
  args.service.workspaceUpdate.calls[0]?.response.reject(new ApiError(412, null));
  args.service.workspaceSettings = { ...args.service.workspaceSettings, version: 2 };
  await userEvent.click(await canvas.findByRole("button", { name: "Review latest" }));
  await expect(await canvas.findByText("Saved version 2")).toBeVisible();
  await userEvent.click(canvas.getByRole("button", { name: "Keep my draft" }));
  await expect(args.service.workspaceUpdate.calls).toHaveLength(1);
  await expect(canvas.getByRole("spinbutton", { name: "Candidate limit" })).toHaveValue(70);
  await userEvent.click(canvas.getByRole("button", { name: "Save workspace settings" }));
  await expect(args.service.workspaceUpdate.calls[1]?.input).toMatchObject({ version: 2, input: { retrieval: { candidateLimit: 70 } } });
} };
